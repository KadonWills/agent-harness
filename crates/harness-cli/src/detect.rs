//! Ecosystem detection for `harness init`: pick an image and the project's
//! own install/test commands so the first `harness run` does real work.

use std::path::Path;

/// What `harness init` found in the repository root.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Detected {
    /// "node", "python", "rust", "go", or "unknown".
    pub ecosystem: &'static str,
    pub image: String,
    pub setup: Vec<String>,
    pub commands: Vec<String>,
}

pub fn detect(root: &Path) -> Detected {
    let has = |name: &str| root.join(name).is_file();
    let read = |name: &str| std::fs::read_to_string(root.join(name)).unwrap_or_default();

    if has("package.json") {
        return node(&read("package.json"), &has);
    }
    if has("pyproject.toml") || has("requirements.txt") || has("setup.py") {
        return python(&has, &read);
    }
    if has("Cargo.toml") {
        return detected(
            "rust",
            "rust:1-slim",
            &["cargo fetch"],
            &["cargo test --offline"],
        );
    }
    if has("go.mod") {
        return detected("go", "golang:1", &["go mod download"], &["go test ./..."]);
    }
    detected("unknown", "debian:bookworm-slim", &[], &[])
}

fn detected(ecosystem: &'static str, image: &str, setup: &[&str], commands: &[&str]) -> Detected {
    Detected {
        ecosystem,
        image: image.to_string(),
        setup: setup.iter().map(|s| s.to_string()).collect(),
        commands: commands.iter().map(|s| s.to_string()).collect(),
    }
}

fn node(package_json: &str, has: &dyn Fn(&str) -> bool) -> Detected {
    let (image, runner, install): (&str, &str, &[&str]) = if has("pnpm-lock.yaml") {
        (
            "node:22-bookworm-slim",
            "pnpm",
            &["corepack enable", "pnpm install --frozen-lockfile"],
        )
    } else if has("yarn.lock") {
        (
            "node:22-bookworm-slim",
            "yarn",
            &["corepack enable", "yarn install --frozen-lockfile"],
        )
    } else if has("bun.lockb") || has("bun.lock") {
        ("oven/bun:1", "bun", &["bun install --frozen-lockfile"])
    } else if has("package-lock.json") {
        ("node:22-bookworm-slim", "npm", &["npm ci"])
    } else {
        ("node:22-bookworm-slim", "npm", &["npm install"])
    };

    let scripts = serde_json::from_str::<serde_json::Value>(package_json)
        .ok()
        .and_then(|v| v.get("scripts").cloned());
    let script = |name: &str| {
        scripts
            .as_ref()
            .and_then(|s| s.get(name))
            .and_then(|s| s.as_str())
            .filter(|s| !s.contains("no test specified"))
            .is_some()
    };
    let mut commands = Vec::new();
    for name in ["build", "test"] {
        if script(name) {
            commands.push(format!("{runner} run {name}"));
        }
    }
    let mut d = detected("node", image, install, &[]);
    d.commands = commands;
    d
}

fn python(has: &dyn Fn(&str) -> bool, read: &dyn Fn(&str) -> String) -> Detected {
    if has("uv.lock") {
        return detected(
            "python",
            "ghcr.io/astral-sh/uv:python3.12-bookworm-slim",
            &["uv sync --frozen"],
            &["uv run pytest"],
        );
    }
    let mut setup = Vec::new();
    let mut manifests = String::new();
    for req in ["requirements.txt", "requirements-dev.txt"] {
        if has(req) {
            setup.push(format!("pip install -r {req}"));
            manifests.push_str(&read(req));
        }
    }
    if has("pyproject.toml") || has("setup.py") {
        setup.push("pip install -e .".to_string());
        manifests.push_str(&read("pyproject.toml"));
    }
    if !manifests.contains("pytest") {
        setup.push("pip install pytest".to_string());
    }
    let mut d = detected("python", "python:3.12-slim", &[], &["python -m pytest"]);
    d.setup = setup;
    d
}

/// Render a commented `harness.toml` for `detected`.
pub fn render(name: &str, base_ref: &str, detected: &Detected) -> String {
    let quote = |s: &str| toml::Value::String(s.to_string()).to_string();
    let list = |items: &[String]| {
        let quoted: Vec<String> = items.iter().map(|s| quote(s)).collect();
        format!("[{}]", quoted.join(", "))
    };
    let setup_egress = !detected.setup.is_empty();
    let hint = if detected.commands.is_empty() {
        "\n# No test command was detected. Add the command that proves a change works,\n\
         # e.g. commands = [\"make test\"]; until then `harness run` executes nothing.\n"
    } else {
        ""
    };
    format!(
        r#"# AgentHarness configuration — generated by `harness init` ({ecosystem} project).
# Schema and every option: https://github.com/KadonWills/agent-harness/blob/main/examples/harness.toml

[project]
name = {name}
base_ref = {base_ref}

[sandbox]
provider = "docker"
image = {image}
allow_egress = false       # zero-trust: validation commands get no network
# Dependency install needs the network. Set this to false (and vendor
# dependencies) to keep the sandbox fully offline.
allow_setup_egress = {setup_egress}
max_memory = "2GB"
timeout = "15m"
max_cpu_time = "10m"

[validation]
setup = {setup}
commands = {commands}
{hint}
[agents]
allowed = []               # e.g. ["claude-code", "cline"]; empty allows any agent
strict_mode = false

[security]
scan_secrets = true
"#,
        ecosystem = detected.ecosystem,
        name = quote(name),
        base_ref = quote(base_ref),
        image = quote(&detected.image),
        setup = list(&detected.setup),
        commands = list(&detected.commands),
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use harness_core::config::HarnessConfig;

    fn detect_files(files: &[(&str, &str)]) -> Detected {
        let dir = tempfile::tempdir().expect("tempdir");
        for (name, content) in files {
            std::fs::write(dir.path().join(name), content).expect("write");
        }
        detect(dir.path())
    }

    #[test]
    fn node_projects_use_their_package_manager_and_scripts() {
        let pkg = r#"{"scripts": {"test": "vitest run", "build": "tsc"}}"#;
        let d = detect_files(&[("package.json", pkg), ("pnpm-lock.yaml", "")]);
        assert_eq!(d.ecosystem, "node");
        assert_eq!(
            d.setup,
            ["corepack enable", "pnpm install --frozen-lockfile"]
        );
        assert_eq!(d.commands, ["pnpm run build", "pnpm run test"]);

        let d = detect_files(&[("package.json", pkg), ("package-lock.json", "{}")]);
        assert_eq!(d.setup, ["npm ci"]);

        let npm_default = r#"{"scripts": {"test": "echo \"Error: no test specified\" && exit 1"}}"#;
        let d = detect_files(&[("package.json", npm_default)]);
        assert!(d.commands.is_empty());
        assert_eq!(d.setup, ["npm install"]);
    }

    #[test]
    fn python_projects_get_pytest() {
        let d = detect_files(&[("requirements.txt", "requests\n")]);
        assert_eq!(d.ecosystem, "python");
        assert_eq!(
            d.setup,
            ["pip install -r requirements.txt", "pip install pytest"]
        );
        assert_eq!(d.commands, ["python -m pytest"]);

        let d = detect_files(&[("pyproject.toml", "[project]\ndependencies = [\"pytest\"]\n")]);
        assert_eq!(d.setup, ["pip install -e ."]);

        let d = detect_files(&[("pyproject.toml", ""), ("uv.lock", "")]);
        assert_eq!(d.commands, ["uv run pytest"]);
    }

    #[test]
    fn other_ecosystems() {
        assert_eq!(detect_files(&[("Cargo.toml", "")]).ecosystem, "rust");
        assert_eq!(detect_files(&[("go.mod", "")]).ecosystem, "go");
        let d = detect_files(&[]);
        assert_eq!(d.ecosystem, "unknown");
        assert!(d.commands.is_empty());
    }

    #[test]
    fn rendered_config_is_valid() {
        for files in [
            vec![("package.json", r#"{"scripts":{"test":"jest"}}"#)],
            vec![("requirements.txt", "")],
            vec![],
        ] {
            let d = detect_files(&files);
            let text = render("my \"app\"", "main", &d);
            let cfg = HarnessConfig::from_toml(&text).expect("generated config parses");
            assert!(cfg.validate().is_empty(), "{:?}\n{text}", cfg.validate());
            assert_eq!(cfg.project.name, "my \"app\"");
            assert_eq!(cfg.sandbox.allow_setup_egress, !d.setup.is_empty());
            assert_eq!(cfg.validation.commands, d.commands);
            assert!(!cfg.sandbox.allow_egress);
        }
    }
}
